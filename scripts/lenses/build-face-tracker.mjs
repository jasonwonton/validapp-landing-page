import { build } from 'esbuild';
import { writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';

// Lens face tracker: a content-hashed worker beside the weekly-game tracker.
// It shares the vendored MediaPipe 0.10.32 runtime and wasm in
// assets/weekly-game/mediapipe-0.10.32; only the model differs.
const result = await build({ entryPoints: ['scripts/lenses/face-worker.js'], bundle: true, format: 'iife', platform: 'browser', target: 'es2020', minify: true, legalComments: 'none', write: false });
const bytes = result.outputFiles[0].contents;
const name = `face-tracker-${createHash('sha256').update(bytes).digest('hex').slice(0, 20)}.js`;
await writeFile(`assets/lenses/${name}`, bytes);
await writeFile('app/lenses/face-tracker-asset.js', `// Generated by scripts/lenses/build-face-tracker.mjs.\nexport const FACE_TRACKER_URL = '/assets/lenses/${name}';\n`);
console.log(name);
